# «Комплектуем только своё» (решение Ивана 2026-07-31): целью комплектации может быть
# лишь наше изделие (`Item.native`). Правило вводится сразу с чисткой существующих
# нарушений — иначе оно осталось бы намерением, а данные жили бы по-старому.
#
# Схему не трогаем: выразить правило CHECK'ом нельзя (оно смотрит в чужую таблицу,
# а MySQL в CHECK подзапросы запрещает). Слои правила — гейт движка
# (`_require_native_target`) + `StockDocument.clean` как страховка для путей мимо
# движка. Здесь только данные.
#
# Что делаем с нарушителями:
#   • ЧЕРНОВИК — снимаем цель. Комплектация без цели с Ф12e законна (её рождают по
#     клику именно такой), человек выберет правильную в форме и ничего не потеряет.
#   • ЗАФИКСИРОВАННАЯ — НЕ трогаем, а громко отчитываемся. У неё есть рождённый
#     лот-прибор и списанные компоненты; снять цель значило бы тихо испортить
#     состоявшийся факт склада. Разбор такой записи (расфиксировать → переделать) —
#     решение человека, а не миграции.
# На снимке dev 2026-07-31 нарушитель ровно один: комплектация-черновик на покупной
# аккумулятор, без строк пайки и рождённых лотов.

from django.db import migrations


def clear_purchased_targets(apps, schema_editor):
    StockDocument = apps.get_model('plume', 'StockDocument')
    bad = StockDocument.objects.filter(kind='kitting', target_item__native=False)

    drafts = bad.filter(locked=False)
    n = drafts.update(target_item=None)
    if n:                       # тишина на чистой базе (аудит-1, Б1а-9)
        print(f'  Комплектации: у {n} черновиков снята покупная цель — выберите наше изделие')

    stuck = list(bad.filter(locked=True).values_list('id', 'code'))
    if stuck:
        print(f'  ! Комплектаций с покупной целью, но зафиксированных: {len(stuck)} — '
              f'{", ".join(c or f"#{i}" for i, c in stuck)}')
        print('  ! не тронуты (за ними рождённые приборы) — разберите руками')


