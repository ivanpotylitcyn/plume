// Тема интерфейса — СЛАГ и его применение. Первый настоящий взнос в шов «движок ↔ вью»
// (волна 21; полный распил — Ф7 волны 19).
//
// Здесь живёт ядро: слаг — это идентичность, он приезжает из движка (`UserProfile.theme`)
// и уезжает туда же. Про ЦВЕТА этот модуль не знает ничего — ни палитры, ни имён
// токенов, ни того, какая из тем светлая. Ярлыки дропдауна — в `themes/registry.ts`,
// значения токенов — в `themes/<слаг>.css`.
//
// Применение — один атрибут на `<html>`: CSS-файл темы прицеплен к
// `:root[data-theme='<слаг>']`, и переключение стоит одну запись в DOM, без перезагрузки,
// без класса на каждом узле и без единой строки в `.tsx` вьюх.

export type ThemeSlug = 'dark' | 'light'

// Дефолт вью совпадает с `models.DEFAULT_THEME`, но НЕ выводится из него: до ответа
// `me()` спрашивать не у кого, а страница должна быть нарисована уже сейчас.
export const DEFAULT_THEME: ThemeSlug = 'dark'

export function applyTheme(slug: string): void {
  document.documentElement.dataset.theme = slug || DEFAULT_THEME
}
