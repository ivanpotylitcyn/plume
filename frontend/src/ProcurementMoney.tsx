// Блок «Деньги» закупки (волна 26; до неё — панель бюджета намерения `IntentBudget`,
// 2026-08-07, общая с заказом, пока заказ не ушёл в сухую сумму по счёту в волне 24).
//
// ★ Закупка — обязательства по счёту там, где позиции закрыты заказами, + оценка остатка
// там, где ещё нет (правило «плана» проекта: факт где есть, оценка где нет). Когда всё
// заказано — число становится чистым фактом: «во сколько обошлась электроника». Рядом:
//
//   заказано по счёту / осталось по оценке — из чего главное число сложилось;
//   оценка закупки — вся закупка по оценке (насколько Plume точен);
//   счёт к оценке — % по заказанным позициям против ТЕКУЩЕЙ оценки (решение Ивана: в
//     активном проекте держим около нуля, перед новым контрактом — «насколько подорожало»);
//   потребность / переплата — сколько из этих денег нужно по-настоящему (2026-08-07).
//
// Все числа считает движок (`procurement_money`, `intent_money`), вью выбирает знак.
import type { ProcurementForm } from './api'
import { StatGroup, StatPanel, StatWarn, Stat } from './StatPanel'
import { count, money, signedPct } from './status'

// Разница со знаком: `+` переплата (взяли с запасом), `−` недозаказ (взяли меньше
// нужды), ноль — «Переплата 0» без знака (решение Ивана 2026-08-07). Цвета нет
// (2026-10-20): блок «Деньги» — информация, см. `Stat`.
// Минус — типографский U+2212: рядом с `+` дефис выглядит короче и ниже.
function overpayStat(overpay: number) {
  if (overpay === 0) return { label: 'переплата', value: money(0) }
  const over = overpay > 0
  return {
    label: over ? 'переплата' : 'недозаказ',
    value: (over ? '+' : '−') + money(Math.abs(overpay)),
  }
}

export function ProcurementMoney({ c }: { c: ProcurementForm }) {
  const op = overpayStat(c.overpay)
  return (
    <StatPanel>
      <Stat main label="закупка" value={money(c.total)}
        note={c.is_fact ? 'факт: всё заказано' : 'факт + оценка остатка'}
        title="Заказано по счёту (зафиксированные заказы) + остаток плана по оценке изделий" />
      <StatGroup>
        <Stat label="заказано по счёту" value={money(c.ordered)}
          title="Цены строк зафиксированных заказов этой закупки — обязательства" />
        <Stat label="осталось по оценке" value={money(c.rest)} dim={c.rest === 0}
          title="Остаток плана сверх заказанного × оценка изделия" />
        <Stat label="оценка закупки" value={money(c.estimate)}
          title="Вся закупка по оценке изделий — насколько точен Plume" />
        <Stat label="счёт к оценке" value={signedPct(c.invoice_gap)}
          dim={c.invoice_gap === null}
          title={'Заказанные позиции: счёт против ТЕКУЩЕЙ оценки. В активном проекте — около'
            + ' нуля (цены свежие); перед новым контрактом — насколько подорожали компоненты'} />
        <Stat label="потребность" value={money(c.demand)}
          title="Сколько эти позиции стоят по потребности проекта — без запаса" />
        <Stat label={op.label} value={op.value}
          title="Разница между закупкой по оценке и реальной потребностью" />
      </StatGroup>
      {c.unestimated.length > 0 &&
        <StatWarn title={'без оценки: ' + c.unestimated.join(', ')}>
          {count(c.unestimated.length, 'позиция', 'позиции', 'позиций')} без оценки — суммы по оценке неполны
        </StatWarn>}
    </StatPanel>
  )
}
